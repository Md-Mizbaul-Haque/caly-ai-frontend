const { calcTotals } = require('../src/utils/totals.js');
let t = calcTotals([{ kcal: 300, protein: 20, carbs: 30, fat: 10 }], 2000);
if (t.eaten !== 300) throw new Error('eaten wrong');
if (t.remaining !== 1700) throw new Error('remaining wrong');
if (t.pct !== 15) throw new Error('pct wrong');
t = calcTotals([], 2000);
if (t.eaten !== 0 || t.pct !== 0) throw new Error('empty wrong');
t = calcTotals([{ kcal: 2500 }], 2000);
if (t.pct !== 100) throw new Error('clamp wrong, got ' + t.pct);
console.log('totals ok');
